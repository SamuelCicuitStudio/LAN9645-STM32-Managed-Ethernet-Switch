/** @brief Returns a bit mask containing only bit @p n. */
#define LAN9645_BIT(n)                (1u << (n))
/** @brief Returns a contiguous bit mask from bit @p l through bit @p h. */
#define LAN9645_GENMASK(h, l)         (((0xFFFFFFFFu >> (31u - (uint32_t)(h))) & 0xFFFFFFFFu) & (0xFFFFFFFFu << (uint32_t)(l)))
/** @brief Returns the least-significant bit position of a field mask. */
#define LAN9645_FIELD_SHIFT(mask)     ((uint32_t)__builtin_ctz((uint32_t)(mask)))
/** @brief Places @p val into a field described by @p mask. */
#define LAN9645_FIELD_PREP(mask, val) ((((uint32_t)(val)) << LAN9645_FIELD_SHIFT(mask)) & (uint32_t)(mask))
/** @brief Extracts a field described by @p mask from register value @p val. */
#define LAN9645_FIELD_GET(mask, val)  ((((uint32_t)(val)) & (uint32_t)(mask)) >> LAN9645_FIELD_SHIFT(mask))

/**
 * @brief Register targets used by the Linux-derived LAN9645 register map.
 *
 * Target values follow the autogenerated LAN9645 tuple format used by the BSP.
 */
typedef enum {
  LAN9645_TARGET_AFI = 0,
  LAN9645_TARGET_ANA = 1,
  LAN9645_TARGET_CHIP_TOP = 2,
  LAN9645_TARGET_CPU = 3,
  LAN9645_TARGET_DEV = 5,
  LAN9645_TARGET_GCB = 16,
  LAN9645_TARGET_HSIO = 17,
  LAN9645_TARGET_QS = 26,
  LAN9645_TARGET_QSYS = 27,
  LAN9645_TARGET_REW = 28,
  LAN9645_TARGET_SYS = 29,
  LAN9645_TARGET_TAS = 30,
  LAN9645_TARGET_COUNT = 38
} lan9645_target_t;

/**
 * @brief Compact description of one register family from the autogenerated map.
 */
typedef struct {
  lan9645_target_t target; /**< Register target block. */
  uint8_t target_instance; /**< First target instance covered by the descriptor. */
  uint8_t target_count;    /**< Number of target instances covered by the descriptor. */
  uint16_t reserved0;      /**< Reserved for alignment. */
  uint32_t group_base;     /**< Base offset of the descriptor's register group. */
  uint32_t group_instance; /**< First group instance covered by the descriptor. */
  uint32_t group_count;    /**< Number of group instances covered by the descriptor. */
  uint32_t group_width;    /**< Address stride between adjacent group instances. */
  uint32_t reg_addr;       /**< Register offset inside the group. */
  uint32_t reg_instance;   /**< First register instance covered by the descriptor. */
  uint32_t reg_count;      /**< Number of register instances covered by the descriptor. */
  uint32_t reg_width;      /**< Address stride between adjacent register instances. */
} lan9645_reg_desc_t;

/** @brief Helper macro used to define a @ref lan9645_reg_desc_t constant. */
#define LAN9645_REG_DESC(_target, _tinst, _tcnt, _gbase, _ginst, _gcnt, _gwidth, _raddr, _rinst, _rcnt, _rwidth) \
  {                                                                                                                  \
    (_target),                                                                                                       \
    (uint8_t)(_tinst),                                                                                               \
    (uint8_t)(_tcnt),                                                                                                \
    0u,                                                                                                              \
    (uint32_t)(_gbase),                                                                                              \
    (uint32_t)(_ginst),                                                                                              \
    (uint32_t)(_gcnt),                                                                                               \
    (uint32_t)(_gwidth),                                                                                             \
    (uint32_t)(_raddr),                                                                                              \
    (uint32_t)(_rinst),                                                                                              \
    (uint32_t)(_rcnt),                                                                                               \
    (uint32_t)(_rwidth)                                                                                              \
  }

/**
 * @brief Resolves the relative register address for one descriptor instance.
 *
 * @param[in] desc Register descriptor to evaluate.
 * @param[in] group_instance Additional group instance offset.
 * @param[in] reg_instance Additional register instance offset.
 *
 * @return Relative address offset before target-base translation.
 */
static inline uint32_t lan9645_reg_desc_rel_addr(
  const lan9645_reg_desc_t *desc,
  uint32_t group_instance,
  uint32_t reg_instance
)
{
  uint32_t grp = desc->group_instance + group_instance;
  uint32_t reg = desc->reg_instance + reg_instance;
  return desc->group_base + (grp * desc->group_width) + desc->reg_addr + (reg * desc->reg_width);
}

